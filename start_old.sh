#!/bin/bash
# =============================================================================
# start_old.sh —— 部分流程启动（老流程，与老项目一致）
#
#   阶段 1  二维码扫描     ：扫码 → 扫到有效码后杀掉扫码链路
#   阶段 2  物块识别       ：检测相机接管 → YOLO 物块识别 → 串口下发 + Web 预览
#
# **跳过障碍物预扫描阶段** —— 与老项目流程完全相同。
#
# 用法:  bash start_old.sh
# =============================================================================

set -u

HOME=/root
WS=$HOME/dev_ws/appli

export CAM_TYPE=usb
export ROS_DOMAIN_ID=42

source /opt/tros/humble/setup.bash
source "$WS/install/setup.bash"

echo "=============================================================="
echo " start_old.sh —— 老流程（二维码 → 物块，跳过障碍物）"
echo " 工作区: $WS"
echo "=============================================================="
echo
echo ">>> 主任务阶段（二维码扫描 → 物块识别）"

cd "$WS" || exit 1
ros2 launch "$WS/launch/run_all.launch.py"
MAIN_RC=$?

echo
echo "=============================================================="
echo " 结束：主任务退出码=$MAIN_RC"
echo "=============================================================="
exit "$MAIN_RC"
